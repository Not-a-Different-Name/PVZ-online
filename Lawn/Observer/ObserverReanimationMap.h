inline bool SameReanimationResource(const char* local,const char* canonical){
 if(!local||!canonical)return false;
 while(*local&&*canonical){unsigned char c=static_cast<unsigned char>(*local++);if(c=='\\')c='/';if(c>='A'&&c<='Z')c+=32;if(c!=static_cast<unsigned char>(*canonical++))return false;}
 return !*local&&!*canonical;
}
inline bool ReanimationToWire(uint32_t local,uint16_t& wire){
 if(local>=gReanimatorDefCount||local>=gReanimationParamArraySize)return false;
 auto* name=gReanimationParamArray[local].mReanimFileName;
 for(uint16_t i=0;i<sizeof(ReanimationResources)/sizeof(*ReanimationResources);++i)if(SameReanimationResource(name,ReanimationResources[i])){wire=i+1;return true;}
 return false;
}
inline bool ReanimationFromWire(uint32_t wire,ReanimationType& local){
 if(!wire||wire>sizeof(ReanimationResources)/sizeof(*ReanimationResources))return false;
 for(uint32_t i=0;i<gReanimationParamArraySize&&i<gReanimatorDefCount;++i)if(SameReanimationResource(gReanimationParamArray[i].mReanimFileName,ReanimationResources[wire-1])){local=ReanimationType(i);return true;}
 return false;
}
