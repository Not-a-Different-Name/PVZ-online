bool RunZombieAllowedOnLevel(ZombieType theZombieType, int theRunLevelIndex)
{
	int aType = (int)theZombieType;
	if (aType < 0 || aType >= 64) return false;

	int aIndex = theRunLevelIndex;
	if (aIndex < 0) aIndex = 0;
	if (aIndex >= RunState::RUN_LEVEL_COUNT) aIndex = RunState::RUN_LEVEL_COUNT - 1;

	unsigned long long aMask = RUN_ZOMBIE_ROSTER[aIndex / RunState::RUN_LEVELS_PER_SCENE][aIndex % RunState::RUN_LEVELS_PER_SCENE];
	return (aMask & (1ULL << aType)) != 0ULL;
}

// @pvz-online: 闯关名单内的类型统一权重（2026-10-03 用户定案"让眼花缭乱的僵尸都出现"）。
// 原版 mPickWeight 里普僵/路障各 4000、门 3500、其余 1000-2000——按权重抽，半个战场都是
// 普僵+路障，贵的怪只是偶尔露脸（2026-10-03 实机反馈）。改成同权后种类分布直接散开，
// 强怪的出现频率交给"买得起"闸（点数）与每波上限管。权重为 0 的特殊类型
//（鸭子圈/旗帜/伴舞——它们不走随机抽取这条通道）保持 0，不开新口子。
static const int RUN_ZOMBIE_PICK_WEIGHT = 1000;

int RunZombieWeight(ZombieType theZombieType)
{
	if (GetZombieDefinition(theZombieType).mPickWeight <= 0)
	{
		return 0;
	}
	return RUN_ZOMBIE_PICK_WEIGHT;
}

int RunLevelIndexForEngineLevel(int theLevel)
{
	// 拿 LevelForIndex 反查、不另写一份除模公式：正反两个方向永远同步，
	// 免得公式改一处忘一处。
	for (int i = 0; i < RunState::RUN_LEVEL_COUNT; i++)
	{
		if (RunState::LevelForIndex(i) == theLevel) return i;
	}
	// 表外的关号（旧构建混搭、迷你游戏之类）一律当第 1 关：宁可出基本怪，也别读穿名单。
	return 0;
}
